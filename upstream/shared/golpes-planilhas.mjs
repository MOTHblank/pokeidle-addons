/**
 * Troca os golpes de cada espécie das tabelas pelos da planilha — todos liberados desde o nível 1.
 *
 * `obter` devolve TODAS as entradas com aquele pokeId, não a primeira: quatro espécies aparecem
 * DUAS vezes na lista do catálogo, uma no espelho e outra em `creatures-novos.json` (#461
 * Weavile, #468 Togekiss, #571 Zoroark, #700 Sylveon). Quem fica de pé é a última — é ela que o
 * `new Map(...)` de `especies` e o `estado.especies.set(...)` do cliente guardam —, então um
 * `find` escreveria na cópia morta e a planilha sumiria em silêncio, sem erro nenhum. Foi o que
 * aconteceu com o Weavile antes desta linha.
 */
export function aplicarGolpesDasPlanilhas(obter) {
  for (const [id, linhas] of TABELAS.flatMap((tabela) => Object.entries(tabela))) {
    for (const esp of obter(Number(id)) ?? []) {
      esp.attacks = linhas.map(([name, type, category, power]) => ({
        name,
        type,
        category,
        power,
        cooldownMs: cooldownDoPoder(power),
        learnLevel: 1,
        ...(power >= 600 ? { categoriaFixa: true } : {}),
      }));
    }
  }
}
